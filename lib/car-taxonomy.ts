function uniqueSorted(values: string[]) {
  return Array.from(new Set(values)).sort((a, b) => a.localeCompare(b, "pt-PT"));
}

export function getBrandOptions(currentBrand?: string | null) {
  const brands = carTaxonomy.map((item) => item.brand);

  if (currentBrand && !brands.includes(currentBrand)) {
    return uniqueSorted([...brands, currentBrand]);
  }

  return uniqueSorted(brands);
}

export function getModelOptions(brand?: string, currentModel?: string | null) {
  const models = carTaxonomy.find((item) => item.brand === brand)?.models ?? [];

  if (currentModel && !models.includes(currentModel)) {
    return uniqueSorted([...models, currentModel]);
  }

  return uniqueSorted(models);
}
